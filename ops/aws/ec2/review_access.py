#!/usr/bin/env python3
"""Render optional staging review configuration; never contact or mutate AWS.

The bootstrap phase serves only ACME challenges publicly. The active phase also
requires a valid certificate and a separately provisioned nginx password file.
Installing outputs and opening ingress require the reviewed operator procedure.
"""
import argparse
import ipaddress
from pathlib import Path


def public_ipv4(value):
    address = ipaddress.IPv4Address(value)
    if not address.is_global:
        raise ValueError("A globally routable IPv4 address is required")
    return str(address)


def render(address, phase):
    address = public_ipv4(address)
    if phase not in ("bootstrap", "active"):
        raise ValueError("Unknown phase")
    private = Path(__file__).with_name("nginx.conf").read_text()
    private = private.replace(
        "# This replaces the packaged default listener. There is NO public HTTP listener.",
        "# Optional STAGING review edge. Generated by review_access.py.",
    )
    public = f'''
  server {{
    listen 80 default_server;
    server_name {address};
    if ($host != {address}) {{ return 444; }}
    location ^~ /.well-known/acme-challenge/ {{
      root /var/lib/apply-acme;
      default_type text/plain;
      try_files $uri =404;
    }}
    location / {{ return 404; }}
  }}
'''
    if phase == "active":
        # Private SSM health probes must also reach Rails' single canonical host.
        # Origin is deliberately NOT rewritten: foreign-browser writes fail CSRF.
        private = private.replace("localhost:8443;", f"{address};")
        private = private.replace("X-Forwarded-Port 8443;", "X-Forwarded-Port 443;")
        public += f'''
  limit_req_zone $binary_remote_addr zone=review_requests:10m rate=10r/s;
  server {{
    listen 443 ssl default_server;
    server_name {address};
    ssl_certificate /etc/letsencrypt/live/apply-staging-review/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/apply-staging-review/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size 1m;
    if ($host != {address}) {{ return 444; }}
    auth_basic "APPly staging - synthetic review only";
    auth_basic_user_file /etc/nginx/apply-review.htpasswd;
    limit_req zone=review_requests burst=40 nodelay;
    limit_req_status 429;
    add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
    add_header Cache-Control "private, no-store" always;
    add_header X-Content-Type-Options nosniff always;
'''
        for location, upstream in (("~ ^/(api(?:/|$)|up$)", "apply_api"), ("/", "apply_web")):
            public += f'''
    location {location} {{
      proxy_pass http://{upstream};
      proxy_set_header Host {address};
      proxy_set_header X-Forwarded-Host {address};
      proxy_set_header X-Forwarded-Proto https;
      proxy_set_header X-Forwarded-Port 443;
      proxy_set_header X-Forwarded-For $remote_addr;
      proxy_set_header X-Real-IP $remote_addr;
      proxy_set_header Forwarded '';
      proxy_set_header Authorization '';
      proxy_read_timeout 60s;
    }}
'''
        public += "  }\n"
    ending = private.rfind("}")
    return private[:ending] + public + private[ending:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ip", required=True)
    parser.add_argument("--phase", choices=("bootstrap", "active"), required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    # Never overwrite an existing output or any host configuration implicitly.
    config = render(args.ip, args.phase)
    with args.output.open("x") as output:
        output.write(config)


if __name__ == "__main__":
    main()
