\getenv runtime_password POSTGRES_RUNTIME_PASSWORD
CREATE ROLE apply_runtime LOGIN PASSWORD :'runtime_password';
GRANT CONNECT ON DATABASE apply TO apply_runtime;
GRANT USAGE, CREATE ON SCHEMA public TO apply_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO apply_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO apply_runtime;
